#!/usr/bin/env node
// Bring Tuple's chord engine into the studio.
//
// Tuple (https://github.com/c0remusic/tuple, MIT) is a Max for Live device: its harmonic logic is one script written
// for Max's [js] object. This copies that script VERBATIM into an ES module, inside a function that hands it the few
// things Max would (outlet, post, Task, LiveAPI…) — see src/host.js for what stands in for them. Nothing of the engine
// is edited (line ends aside), so a new Tuple release is one run of this script and a look at the tests.
//
//   node packages/chord-grid/scripts/vendor-tuple.mjs <path to a checkout of c0remusic/tuple>
//
// Writes src/tuple-engine.js (generated, not linted), src/tuple-source.js (where it came from) and LICENSE-tuple.txt.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(HERE, '..');
const from = process.argv[2] && path.resolve(process.argv[2]);
const file = from && path.join(from, 'device', 'tuple_chord_engine.js');
if (!from || !fs.existsSync(file)) {
  console.error('usage: node packages/chord-grid/scripts/vendor-tuple.mjs <path to a checkout of c0remusic/tuple>');
  process.exit(1);
}
const raw = fs.readFileSync(file);
// (the copy is the file's own bytes, with Unix line ends and one newline at the end: the hash below is of that text)
const src = `${raw.toString('utf8').replace(/\r\n/g, '\n').trimEnd()}\n`;
const licence = fs.readFileSync(path.join(from, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n');
if (!/MIT License/.test(licence)) throw new Error('The licence of that checkout is not MIT any more: read it before going on');
const version = fs.readFileSync(path.join(from, 'VERSION'), 'utf8').trim();
const commit = execFileSync('git', ['-C', from, 'rev-parse', 'HEAD']).toString().trim();
const sha256 = crypto.createHash('sha256').update(src).digest('hex');
const upstreamSha256 = crypto.createHash('sha256').update(raw).digest('hex');

// Every function the script declares at its top level: Max calls them by name (a message "seven 0" is seven(0)), and so
// does the studio's adapter.
const fns = [...new Set([...src.matchAll(/^function ([A-Za-z_$][\w$]*)\s*\(/gm)].map((m) => m[1]))];
// What the adapter (src/index.js) uses beside the messages the engine sends: the functions it calls and the variables
// it reads or sets — read off the adapter itself, so the two cannot drift. Each must still be at the top level of the
// script: a rename upstream stops here, with its name, not in a user's session.
const adapter = fs.readFileSync(path.join(PKG, 'src', 'index.js'), 'utf8');
const used = (re) => [...new Set([...adapter.matchAll(re)].map((m) => m[1]))];
const CALLS = used(/\b(?:fns\.|send\('|act\(')([A-Za-z_$][\w$]*)/g);
const READ = used(/\beng\.get\('([A-Za-z_$][\w$]*)'/g);
const WRITE = used(/\beng\.set\('([A-Za-z_$][\w$]*)'/g);
if (CALLS.length < 20 || READ.length < 5) throw new Error('Could not read what src/index.js uses of the engine');
for (const name of new Set([...READ, ...WRITE])) {
  if (!new RegExp(`^var [^;\\n]*\\b${name.replace(/\$/g, '\\$')}\\b`, 'm').test(src)) throw new Error(`The engine has no top-level variable "${name}" any more: the adapter (src/index.js) uses it — see what replaced it`);
}
for (const name of CALLS) {
  if (!fns.includes(name)) throw new Error(`The engine has no function ${name}() any more: the adapter (src/index.js) calls it — see what replaced it`);
}

const comment = (text) => text.trimEnd().split('\n').map((l) => `// ${l}`.trimEnd()).join('\n');
const out = `// GENERATED by scripts/vendor-tuple.mjs — do not edit: change the script, or run it on a newer Tuple.
//
// Between the two marked lines below is device/tuple_chord_engine.js of Tuple ${version}, as its authors wrote it —
// only its line ends are Unix ones here (https://github.com/c0remusic/tuple, commit ${commit};
// sha256 of the text below ${sha256}).
// Its comments are in French, as its authors wrote them. Tuple is distributed under this licence:
//
${comment(licence)}
//
/* eslint-disable */
export function createTupleEngine(host) {
  // what Max gives a [js] object, from the host (src/host.js)
  var outlet = host.outlet, post = host.post, messnamed = host.messnamed, Task = host.Task, LiveAPI = host.LiveAPI, File = host.File;
  var Math = host.Math, max = host.max, jsarguments = host.jsarguments;
  var autowatch, outlets, inlets, inlet = 0, messagename = '';
// ======================================================================== tuple_chord_engine.js: verbatim from here
${src}// ======================================================================== tuple_chord_engine.js: to here
  return {
    fns: { ${fns.map((n) => `${n}: ${n}`).join(', ')} },
    get: function (name) {
      switch (name) {
${READ.map((n) => `        case '${n}': return ${n};`).join('\n')}
        default: throw new Error('chord-grid: the engine variable "' + name + '" is not exposed (scripts/vendor-tuple.mjs)');
      }
    },
    set: function (name, value) {
      switch (name) {
${WRITE.map((n) => `        case '${n}': ${n} = value; break;`).join('\n')}
        default: throw new Error('chord-grid: the engine variable "' + name + '" cannot be set (scripts/vendor-tuple.mjs)');
      }
    }
  };
}
`;
fs.writeFileSync(path.join(PKG, 'src', 'tuple-engine.js'), out);
fs.writeFileSync(path.join(PKG, 'src', 'tuple-source.js'), `// GENERATED by scripts/vendor-tuple.mjs: where src/tuple-engine.js came from.
export const TUPLE_SOURCE = ${JSON.stringify({ name: 'Tuple', author: 'c0remusic', license: 'MIT', repository: 'https://github.com/c0remusic/tuple', version, commit, file: 'device/tuple_chord_engine.js', sha256, upstreamSha256 }, null, 2).replace(/"([a-z0-9]+)":/gi, '$1:').replace(/"/g, "'")};
`);
fs.writeFileSync(path.join(PKG, 'LICENSE-tuple.txt'), licence);

// it must load as a module (strict mode, no HTML comments…): find out now
const mod = await import(`${pathToFileURL(path.join(PKG, 'src', 'tuple-engine.js')).href}?t=${Date.now()}`);
if (typeof mod.createTupleEngine !== 'function') throw new Error('The generated module does not export createTupleEngine');
console.log(`Tuple ${version} (${commit.slice(0, 7)}): ${fns.length} functions (${CALLS.length} called, ${READ.length} variables read, ${WRITE.length} set), ${(out.length / 1024).toFixed(0)} KB → src/tuple-engine.js. Now: npm test -w packages/chord-grid`);
